/**
 * Calculates damage dealt by a single bullet/pellet at a given distance,
 * accounting for linear distance falloff and headshot multiplier.
 */
export function calculateWeaponDamage(
  weapon: WeaponDefinition,
  distance: number,
  isHeadshot: boolean
): number {
  let distanceMultiplier = 1.0;
  if (distance <= weapon.falloffStart) {
    distanceMultiplier = 1.0;
  } else if (distance >= weapon.falloffEnd) {
    distanceMultiplier = weapon.minDamageMultiplier;
  } else {
    const t =
      (distance - weapon.falloffStart) /
      Math.max(0.001, weapon.falloffEnd - weapon.falloffStart);
    distanceMultiplier = 1.0 + t * (weapon.minDamageMultiplier - 1.0);
  }

  const headMult = isHeadshot ? weapon.headshotMultiplier : 1.0;
  return Math.max(1, Math.round(weapon.baseDamage * distanceMultiplier * headMult));
}
